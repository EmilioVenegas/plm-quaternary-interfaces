warnings.filterwarnings("ignore")

REPO = Path(__file__).resolve().parents[1]
STRUCT_DIR = REPO / "data" / "structures"
DMS_DIR = REPO / "data" / "proteingym" / "DMS_substitutions"
REF_CSV = Path("/tmp/dms_substitutions.csv")  # ProteinGym DMS_substitutions.csv v1.3
OUT_DIR = REPO / "analysis" / "results"
OUT_DIR.mkdir(parents=True, exist_ok=True)

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
MODEL_NAME = "facebook/esm2_t33_650M_UR50D"
AA_LIST = list("ACDEFGHIKLMNPQRSTVWY")
CUTOFF = 3.0  # Angstrom, first-shell donor-atom distance (BioLiP/MetalPDB convention)

DONOR_ATOMS = {
    "CYS": ["SG"], "HIS": ["ND1", "NE2"], "ASP": ["OD1", "OD2"], "GLU": ["OE1", "OE2"],
    "MET": ["SD"], "SER": ["OG"], "THR": ["OG1"], "TYR": ["OH"],
    "ASN": ["OD1", "ND2"], "GLN": ["OE1", "NE2"], "LYS": ["NZ"],
}
FAMILY = {
    "C": "thiolate", "H": "imidazole",
    "D": "carboxylate", "E": "carboxylate", "N": "carboxylate", "Q": "carboxylate",
    "S": "hydroxyl", "T": "hydroxyl", "Y": "hydroxyl",
    "K": "amine", "R": "amine",
}

# --- verified site table (see docstring for provenance of every position) ---
SITES = (
    [("A4GRB6_PSEAI_Chen_2020", p, True, "Zn") for p in (114, 116, 118, 179, 198, 240)]
    + [("CALM1_HUMAN_Weile_2017", p, True, "Ca")
       for p in (21, 23, 25, 32, 57, 59, 61, 68, 94, 96, 98, 105, 130, 132, 134, 141)]
    + [(d, 435, True, "Fe-heme") for d in
       ("CP2C9_HUMAN_Amorosi_2021_activity", "CP2C9_HUMAN_Amorosi_2021_abundance")]
    + [("PPM1D_HUMAN_Miller_2022", p, True, "Mg") for p in (105, 314, 366)]
    + [("GAL4_YEAST_Kitzman_2015", p, True, "Zn(Cd-surrogate)") for p in (11, 14, 21, 28, 31, 38)]
    + [("NUD15_HUMAN_Suiter_2020", p, True, "Mg") for p in (63, 67)]
    + [(d, p, False, None)
       for d in ("BLAT_ECOLX_Deng_2012", "BLAT_ECOLX_Firnberg_2014",
                 "BLAT_ECOLX_Jacquier_2013", "BLAT_ECOLX_Stiffler_2015")
       for p in (68, 71, 128, 164, 232)]
)


def family(aa):
    return FAMILY.get(aa, "other")


def load_ref_rows():
    return {r["DMS_id"]: r for r in csv.DictReader(open(REF_CSV))}


@torch.no_grad()
def masked_marginal_logprobs(model, tokenizer, seq, positions):
    out = {}
    for pos in positions:
        toks = tokenizer(seq, return_tensors="pt").to(DEVICE)
        toks["input_ids"][0, pos] = tokenizer.mask_token_id
        logits = model(**toks).logits[0, pos]
        logprobs = F.log_softmax(logits, dim=-1)
        out[pos] = {aa: logprobs[tokenizer.convert_tokens_to_ids(aa)].item() for aa in AA_LIST}
    return out


def parse_mutant(m):
    return m[0], int(m[1:-1]), m[-1]


def interaction_stat(d):
    m_comp = d[(d.is_metal) & (d.same_family)]["residual"].mean()
    m_incomp = d[(d.is_metal) & (~d.same_family)]["residual"].mean()
    c_comp = d[(~d.is_metal) & (d.same_family)]["residual"].mean()
    c_incomp = d[(~d.is_metal) & (~d.same_family)]["residual"].mean()
    return (m_comp - m_incomp) - (c_comp - c_incomp)


def stratified_permutation_test(df, strata, n_perm=10000, seed=0):
    rng = np.random.default_rng(seed)
    observed = interaction_stat(df)
    stats_null = np.zeros(n_perm)
    for i in range(n_perm):
        d2 = df.copy()
        sf = d2["same_family"].values.copy()
        for idx in strata:
            idx = np.array(idx)
            sf[idx] = rng.permutation(sf[idx])
        d2["same_family"] = sf
        stats_null[i] = interaction_stat(d2)
    p = (np.abs(stats_null) >= np.abs(observed)).mean()
    return observed, p, stats_null


def main():
    ref_rows = load_ref_rows()
    site_df = pd.DataFrame(SITES, columns=["DMS_id", "pos", "is_metal", "metal"])
    site_df["wt_aa"] = site_df.apply(lambda r: ref_rows[r["DMS_id"]]["target_seq"][r["pos"] - 1], axis=1)
    site_lookup = {(r["DMS_id"], r["pos"]): r for _, r in site_df.iterrows()}

    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
    model = AutoModelForMaskedLM.from_pretrained(MODEL_NAME).to(DEVICE).eval()

    unique_by_protein = site_df.groupby("DMS_id")["pos"].apply(lambda s: sorted(set(s))).to_dict()
    logprob_cache = {}
    for dms_id, positions in unique_by_protein.items():
        seq = ref_rows[dms_id]["target_seq"]
        res = masked_marginal_logprobs(model, tokenizer, seq, positions)
        for p, v in res.items():
            logprob_cache[(dms_id, p)] = v

    rows = []
    for dms_id, positions in unique_by_protein.items():
        df_assay = pd.read_csv(DMS_DIR / f"{dms_id}.csv")
        posset = set(positions)
        for _, row in df_assay.iterrows():
            mutant_str = row["mutant"]
            if ":" in mutant_str:
                continue
            wt, pos, mut = parse_mutant(mutant_str)
            if pos not in posset:
                continue
            info = site_lookup[(dms_id, pos)]
            if wt != info["wt_aa"]:
                continue
            lp = logprob_cache[(dms_id, pos)]
            rows.append({
                "DMS_id": dms_id, "protein": dms_id.split("_")[0], "pos": pos,
                "wt": wt, "mut": mut, "is_metal": info["is_metal"], "metal": info["metal"],
                "zeroshot_score": lp[mut] - lp[wt],
                "same_family": family(mut) == family(wt),
                "DMS_score": row["DMS_score"],
            })

    df = pd.DataFrame(rows)
    df["DMS_z"] = df.groupby("DMS_id")["DMS_score"].transform(lambda x: (x - x.mean()) / x.std())
    df["zs_z"] = df.groupby("DMS_id")["zeroshot_score"].transform(lambda x: (x - x.mean()) / x.std())
    df["residual"] = df["DMS_z"] - df["zs_z"]

    strata = list(df.groupby(["DMS_id", "is_metal"]).groups.values())
    observed, p_val, _ = stratified_permutation_test(df, strata)

    df.to_csv(OUT_DIR / "analysis_dataset.csv", index=False)
    summary = {
        "n_total": len(df), "n_metal": int(df.is_metal.sum()), "n_control": int((~df.is_metal).sum()),
        "spearman_zeroshot_vs_dms_metal": stats.spearmanr(df[df.is_metal]["zeroshot_score"], df[df.is_metal]["DMS_score"]),
        "spearman_zeroshot_vs_dms_control": stats.spearmanr(df[~df.is_metal]["zeroshot_score"], df[~df.is_metal]["DMS_score"]),
        "interaction_stat_observed": observed,
        "interaction_permutation_p": p_val,
        "conclusion": "NOT significant at pre-registered p<0.01 -- H1 not supported (see docstring).",
    }
    with open(OUT_DIR / "summary.json", "w") as f:
        json.dump(summary, f, indent=2, default=str)
    print(json.dumps(summary, indent=2, default=str))


if __name__ == "__main__":
    main()
