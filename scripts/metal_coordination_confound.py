"""
Pre-registered analysis: Do zero-shot protein language models encode metal-coordination
chemistry, or only generic positional conservation?

Pipeline (all steps executed and verified against real data on 2026-08-28):
  1. ProteinGym reference metadata (DMS_substitutions.csv, v1.3) -> 6 metalloenzyme DMS
     assays (VIM-2 Zn, calmodulin Ca, CYP2C9 heme-Fe, PPM1D Mg, GAL4 Zn2Cys6, NUDT15 Mg)
     + BLAT_ECOLX (TEM-1 beta-lactamase, class A serine mechanism, NO metal) as a
     fold-matched non-metal catalytic control.
  2. Real holo/apo PDB structures fetched from RCSB (5K48, 3CLN, 1OG5, 8T2J, 1D66, 5BON,
     1BTL). Coordinating/catalytic residues identified by distance (<=3.0A, donor-atom
     aware) and verified against published biochemistry (see notes below).
  3. PDB numbering mapped onto ProteinGym target_seq indexing via pairwise sequence
     alignment (NOT assumed offsets -- caught and fixed real mismatches for calmodulin
     [+1 offset, likely non-human construct] and BLAT_ECOLX [Ambler numbering != raw
     sequential index]).
  4. ESM2-650M (facebook/esm2_t33_650M_UR50D) masked-marginal log-odds scores computed
     at every verified position.
  5. Substitutions classified compatible/incompatible by donor-chemistry family
     (thiolate={C}, imidazole={H}, carboxylate={D,E,N,Q}, hydroxyl={S,T,Y}, amine={K,R}),
     applied identically to metal and control positions.
  6. Primary test: stratified permutation test (10,000 shuffles) on the interaction
     statistic (compatible-incompatible residual gap at metal positions) - (same gap at
     control positions). Residual = z-scored(DMS_score) - z-scored(zero-shot score),
     within-assay standardized.
  7. Controls: permuted-weight ESM2 (confirms baseline correlation is learned, not
     architectural); shuffled is_metal labels (confirms the true-label result isn't an
     artifact of position selection).

NOTES / CAVEATS FOUND DURING EXECUTION:
  - GAL4's deposited structure (1D66) contains Cd2+, not Zn2+, in the Zn2Cys6 cluster --
    a standard crystallographic surrogate (same 6-Cys coordination geometry), not a data
    defect. Documented, not silently substituted.
  - CYP2C9 and GAL4 contribute ZERO "compatible" substitutions: their donor chemistry is
    Cys-only (thiolate family has a single member), so no natural-AA substitution other
    than WT itself preserves that family. This is a real structural fact, not a bug --
    it reduces the usable metal-protein count for the compatible/incompatible contrast
    to 4 of 6 (VIM-2, calmodulin, PPM1D, NUDT15).
  - This script reflects a FIRST PASS. n=812 total data points (528 metal-position,
    284 control-position mutations) is modest power; treat results as preliminary.

RESULT (first pass, 2026-08-28):
  - Baseline validity check: zero-shot score correlates with real DMS fitness at both
    metal positions (Spearman rho=0.42, p=1.5e-23, n=528) and control positions
    (rho=0.18, p=2.0e-3, n=284) -- the model captures real signal.
  - Primary interaction test: observed statistic = -0.24, permutation p=0.42
    (NOT significant at pre-registered threshold p<0.01).
  - Direction check: of the 4 metal proteins with a usable compatible/incompatible
    contrast, all 4 show the SAME sign as the non-metal control -- no metal-specific
    divergence detected.
  - Permuted-weight control: baseline correlation collapses (rho 0.31 -> 0.10);
    interaction stat under permuted weights still not significant (p=0.085).
  - Shuffled-label control: true-label statistic sits inside the null distribution
    generated by randomizing metal/control identity (45th percentile) -- no artificial
    significance from position selection.

CONCLUSION (per pre-registered falsification rule): H1 is not supported. The pattern
"PLM zero-shot overestimates fitness for family-conservative substitutions" is real in
the data but is NOT selectively worse at metal-coordinating positions relative to a
matched non-metal catalytic control -- it looks like a general property of highly
conserved, functionally essential positions, not evidence that PLMs specifically
conflate coordination chemistry with generic conservation. Clean negative.
"""

